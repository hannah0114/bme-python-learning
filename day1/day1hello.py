# ========== Day2 基础数据类型练习 ==========
# 1.整数 int
a = 10
print("整数 a =", a, type(a))

# 2.浮点数 float
b = 3.14
print("浮点数 b =", b, type(b))

# 3.字符串 str
c = "生物医学工程"
print("字符串 c =", c, type(c))

# 4.布尔值 bool
d = True
print("布尔值 d =", d, type(d))

# 5.列表 list
e = [1, 2, 3, "探针", "成像"]
print("列表 e =", e, type(e))

# 6.元组 tuple
f = (10, 20, 30)
print("元组 f =", f, type(f))

# 7.字典 dict
g = {"name":"分子影像", "year":2026}
print("字典 g =", g, type(g))

# 8.空值 None
h = None
print("空值 h =", h, type(h))